/**
 * Index whatever is sitting in public/proof/screenshots/ into a data module
 * the landing page can import.
 *
 * Runs automatically before every build (npm's `prebuild` hook), so adding a
 * customer screenshot to the proof wall is a file upload and nothing else —
 * drag it into that folder on GitHub, commit, and it is on the page when the
 * deploy finishes. No code change, no developer in the loop. That matters:
 * the person with the screenshots is not the person editing lib/landing.ts,
 * and a proof wall only stays current if keeping it current is trivial.
 *
 * Order is filename order, so prefixing 01-, 02- controls the layout.
 *
 * Captions are optional. Drop a captions.json next to the images —
 *   { "01-mike.png": "PSA Birth Certificate, delivered to Isabela" }
 * — and any filename it mentions gets that line underneath. Anything it does
 * not mention simply has no caption.
 *
 * Run by hand:  node scripts/index-screenshots.mjs
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const DIR = "public/proof/screenshots";
const OUT = "lib/data/proof-screenshots.ts";
const IMAGE = /\.(png|jpe?g|webp|avif|gif)$/i;

const files = existsSync(DIR)
  ? readdirSync(DIR)
      .filter((f) => IMAGE.test(f))
      .sort((a, b) => a.localeCompare(b, "en", { numeric: true }))
  : [];

let captions = {};
const captionFile = join(DIR, "captions.json");
if (existsSync(captionFile)) {
  try {
    captions = JSON.parse(readFileSync(captionFile, "utf8"));
  } catch (err) {
    // A malformed captions.json must not take the whole build down over a
    // trailing comma — the images are the point, the captions are a nicety.
    console.warn(`[screenshots] ignoring ${captionFile}: ${err.message}`);
  }
}

const entries = files.map((name) => {
  const caption = typeof captions[name] === "string" ? captions[name] : null;
  return (
    `  {\n` +
    `    src: ${JSON.stringify(`/proof/screenshots/${name}`)},\n` +
    `    alt: ${JSON.stringify(
      caption ?? "A customer's message about the document we delivered"
    )},\n` +
    (caption ? `    caption: ${JSON.stringify(caption)},\n` : "") +
    `  },`
  );
});

writeFileSync(
  OUT,
  `// GENERATED by scripts/index-screenshots.mjs — do not edit by hand.\n` +
    `// Add or remove files in ${DIR}/ instead; the next build rewrites this.\n` +
    `import type { ProofShot } from "@/lib/landing";\n\n` +
    `export const PROOF_SCREENSHOT_FILES: ProofShot[] = [\n` +
    (entries.length ? entries.join("\n") + "\n" : "") +
    `];\n`
);

console.log(`[screenshots] indexed ${files.length} file(s) into ${OUT}`);
